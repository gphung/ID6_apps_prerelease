"""Build a DME fault-description table for EngineCodes from bmw-unified-db.

Two steps, so the BMW-derived German source text stays outside the repository:

  extract  bmw.sqlite SGBD out.csv
      Writes code,german for the SGBD's fault memory (FORTTEXTE), one row per code.
  header   translated.csv SGBD SGBD_INDEX DB_SHA256 DB_REVISION out.h
      Reads code,german,english and writes the C table. Every code from the extract must
      have a non-empty English text; nothing is added or dropped.

The F87 M2 N55 table uses SGBD mevd172y (MEVD17.2 / 17.2.6 / 17.2.G, SGBD index 0xF1910).
"""
import csv
import re
import sqlite3
import sys

CODE = re.compile(r'^0x[0-9A-F]{6}$')


def extract(database, sgbd, out):
    db = sqlite3.connect('file:%s?mode=ro' % database, uri=True)
    rows = db.execute("SELECT code, location_text FROM dtc WHERE sgbd=? AND source_table='FORTTEXTE' "
                      "ORDER BY code", (sgbd,)).fetchall()
    codes = [code for code, _ in rows]
    if not rows or len(codes) != len(set(codes)) or not all(CODE.match(c) for c in codes):
        raise SystemExit('unexpected fault memory rows for %s' % sgbd)
    with open(out, 'w', newline='', encoding='utf-8') as f:
        writer = csv.writer(f)
        writer.writerow(('code', 'german'))
        writer.writerows(rows)
    print('%d codes for %s' % (len(rows), sgbd))


def c_string(text):
    if not text or any(ord(ch) < 32 or ord(ch) > 126 for ch in text):
        raise SystemExit('English text must be printable ASCII: %r' % text)
    return '"%s"' % text.replace('\\', '\\\\').replace('"', '\\"')


def header(translated, sgbd, index, digest, revision, out):
    with open(translated, newline='', encoding='utf-8') as f:
        rows = list(csv.DictReader(f))
    codes = [row['code'] for row in rows]
    if len(codes) != len(set(codes)) or not all(CODE.match(c) for c in codes):
        raise SystemExit('codes must be unique 0xXXXXXX values')
    lines = ['// Generated by tools/make_dme_descriptions.py. Do not edit by hand.',
             '// F87 M2 N55 DME fault memory: SGBD %s (SGBD index %s),' % (sgbd, index),
             '// bmw-unified-db %s, bmw.sqlite SHA-256 %s.' % (revision, digest),
             '// English texts are translations of the German FORTTEXTE location texts.',
             'static const struct DmeDescription kN55DmeDescriptions[] = {']
    for row in sorted(rows, key=lambda r: int(r['code'], 16)):
        lines.append('    {%s, %s},' % (row['code'], c_string(row['english'].strip())))
    lines.append('};')
    with open(out, 'w', encoding='ascii') as f:
        f.write('\n'.join(lines) + '\n')
    print('%d descriptions written to %s' % (len(rows), out))


if __name__ == '__main__':
    if len(sys.argv) == 5 and sys.argv[1] == 'extract':
        extract(*sys.argv[2:])
    elif len(sys.argv) == 8 and sys.argv[1] == 'header':
        header(*sys.argv[2:])
    else:
        raise SystemExit(__doc__)
